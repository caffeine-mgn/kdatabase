package pw.binom.db

/**
 * Как СУБД защищает строку от параллельной записи.
 *
 * ## Зачем это в контракте, а не флаг в ORM
 *
 * «Заблокировать строку» звучит одинаково, но достигается по-разному:
 *
 * * **Postgres** умеет `SELECT ... FOR UPDATE` — блокировка на уровне строки,
 *   снимается в конце транзакции. Две транзакции над разными строками друг
 *   другу не мешают.
 * * **SQLite** не знает `FOR UPDATE` вовсе (проверено: `near "FOR": syntax
 *   error`). Зато `BEGIN IMMEDIATE` берёт блокировку записи на **всю** базу
 *   в момент начала транзакции, и гонки не остаётся физически.
 * * **MySQL** с InnoDB — как Postgres; с MyISAM — никак.
 *
 * Поэтому ORM должна спрашивать у драйвера не «умеешь ли ты FOR UPDATE»,
 * а «как у тебя делается блокировка». Иначе получается либо SQL, который
 * падает на SQLite, либо тихое отсутствие блокировки там, где её ждут.
 *
 * ## Что обязан сделать драйвер
 *
 * * [ROW_LOCK] — реализовать `SqlDialect.forUpdateClause()`, ORM подставит
 *   результат в конец `SELECT`.
 * * [TRANSACTION_LOCK] — гарантировать, что транзакция блокирует запись с
 *   самого начала (`BEGIN IMMEDIATE` в SQLite). Суффикс к `SELECT` не
 *   добавляется: там его не бывает.
 * * [NONE] — ORM обязана бросить исключение, если блокировку запросили
 *   явно. Молча проигнорировать значит отдать вызывающему ложную гарантию.
 */
enum class LockStrategy {
    /** `SELECT ... FOR UPDATE`: блокировка строки до конца транзакции. */
    ROW_LOCK,

    /**
     * Блокировка на уровне транзакции: запись блокируется целиком.
     *
     * Гранулярность грубее, зато гарантия строже — гонки нет вообще, а не
     * только по выбранной строке.
     */
    TRANSACTION_LOCK,

    /** Блокировки нет. Запрос блокировки должен падать, а не притворяться. */
    NONE,
}

/**
 * Диалект: то, что ORM должна знать о СУБД помимо кавычек.
 *
 * Отдельно от [DatabaseInfo], потому что это не «сведения», а поведение:
 * методы возвращают фрагменты SQL. Держать их в одном интерфейсе значило бы
 * смешать данные и генерацию.
 */
interface SqlDialect {
    /**
     * Суффикс для блокирующего чтения.
     *
     * Возвращает `"FOR UPDATE"` для [LockStrategy.ROW_LOCK] и пустую строку
     * для остальных. Пустая строка для [LockStrategy.NONE] намеренно не
     * означает «нет блокировки» — вызывающий обязан проверить стратегию
     * сам, иначе получит тихое отсутствие гарантии.
     */
    fun forUpdateClause(): String

    /** Как стратегия блокировки выглядит снаружи. */
    val lockStrategy: LockStrategy
}
