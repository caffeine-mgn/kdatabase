package pw.binom.db.pool

import pw.binom.db.Connection

/**
 * Пул соединений.
 *
 * ## Что здесь главное
 *
 * Пул решает две задачи, и путать их нельзя:
 *
 * 1. **Ограничить число соединений.** У БД есть предел, и упереться в него
 *    хуже, чем подождать. Поэтому [maxConnections] — жёсткий потолок:
 *    при исчерпании вызывающий ждёт, а не получает новое соединение.
 * 2. **Переиспользовать.** Открытие соединения — сетевой хендшейк с SASL,
 *    это десятки миллисекунд.
 *
 * ## Почему `withConnection`, а не `borrow`/`free`
 *
 * Пара `borrow`/`free` протекает: если между ними исключение, соединение
 * теряется. А ещё она не даёт выразить транзакцию — та занимает соединение
 * на всё время блока, а не на один запрос.
 *
 * `withConnection` возвращает соединение сам, в `finally`, и по типу
 * исключения решает, годится ли оно дальше.
 *
 * ## Что делает пул при ошибке
 *
 * * [pw.binom.db.ConnectionLostException] → соединение уничтожается, из
 *   набора убирается, освобождается слот;
 * * остальные исключения → соединение возвращается в набор. Но только если
 *   клиент не пометил его битым через [PooledConnection.markBroken].
 *
 * Соединение, у которого открыта транзакция, в набор не возвращается:
 * неизвестно, закоммичена ли она, и следующий клиент унаследует чужое
 * состояние.
 */
interface ConnectionPool : AutoCloseable {
    val maxConnections: Int

    /** Сколько соединений открыто сейчас. */
    val connectionCount: Int

    /** Сколько простаивает. */
    val idleCount: Int

    /** Сколько вызывающих ждёт свободное соединение. */
    val waitingCount: Int

    /** Счётчик открытых за всё время — для метрик и отладки утечек. */
    val totalCreated: Long

    /** Сколько раз ждали дольше таймаута. */
    val timeouts: Long

    suspend fun acquire(): PooledConnection

    /**
     * Выполнить блок, заняв соединение на всё его время.
     *
     * Соединение возвращается в пул автоматически. Исключение пробрасывается
     * дальше, а решение о судьбе соединения принимается по его типу.
     */
    suspend fun <T> withConnection(block: suspend (PooledConnection) -> T): T

    /**
     * Проверить набор: пингануть простаивающие, закрыть просроченные.
     *
     * Живость — это [PoolConfig.pingQuery] и, следом, слово драйвера
     * ([ConnectionFactory.validate]); любое «нет» закрывает соединение.
     *
     * Возвращает число закрытых. Вызывается из [withConnection] и [acquire]
     * автоматически; отдельно — для периодической уборки по таймеру.
     */
    suspend fun cleanUp(): Int
}
