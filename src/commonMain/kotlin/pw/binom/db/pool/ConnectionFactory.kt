package pw.binom.db.pool

import pw.binom.db.Connection

/**
 * Точка, которой драйвер участвует в жизни соединения.
 *
 * ## Зачем
 *
 * Механика пула — очередь, слоты, пинг, уборка по времени, возврат — у всех
 * СУБД одна. Разными были бы только её копии, а копия в четыреста строк
 * означает, что одну и ту же ошибку придётся чинить столько раз, сколько
 * драйверов. Поэтому пул остаётся в `kdatabase` как есть, а драйвер получает
 * способ влиять на создание и уничтожение соединения, не переписывая механику.
 *
 * Драйвер передаёт свою реализацию в [ConnectionPoolImpl] и описывает в ней
 * только своё: Postgres — параметры сессии, SQLite — `WAL` и `busy_timeout`.
 *
 * ## Чего здесь нет
 *
 * Нет `close`: соединение закрывает пул через [Connection.close], иначе два
 * владельца спорили бы за один ресурс. Нет и «исполнить запрос» — это дело
 * соединения, а не пула.
 */
interface ConnectionFactory {

    /**
     * Открыть соединение.
     *
     * Вызывается лениво: пул открывает соединение только когда слот
     * действительно разыгран ([PoolConfig.maxConnections] позволяет). Поэтому
     * конструктор пула не падает, если база ещё стартует, — падает первый
     * запрос.
     *
     * Исключение из этой функции пул транслирует вызывающему, а слот
     * освобождает; соединение в набор не попадает.
     */
    suspend fun open(): Connection

    /**
     * Проверка живости дополнительно к [PoolConfig.pingQuery].
     *
     * Вызывается в [ConnectionPool.cleanUp] на тех же основаниях, что и
     * `pingQuery`: соединение простаивало дольше `pingInterval`. Сначала
     * выполняется запрос-пинг (если он задан), затем — здесь.
     *
     * `false` означает «соединение уничтожить», и это единственный способ
     * драйверу сказать пулу что-то, чего не видно по `SELECT 1`: живой сокет
     * при ушедшем в аварийку серверном процессе, сессия с сброшенными
     * настройками, файл SQLite, переписанный соседним процессом.
     *
     * По умолчанию `true`: большинству драйверов хватает пинга.
     */
    suspend fun validate(connection: Connection): Boolean = true

    /**
     * Соединение уничтожается: разрыв, просрочка `idleTimeout`/`maxLifetime`,
     * проваленная проверка живости.
     *
     * Вызывается после [Connection.close] и нужен для того, что close не
     * делает: освободить серверный ресурс, снять advisory-блокировку, убрать
     * временный файл.
     *
     * Вызов отложенный: он исполняется на следующем `suspend`-входе в пул
     * ([ConnectionPool.acquire], [ConnectionPool.withConnection],
     * [ConnectionPool.cleanUp]). Пул не заводит своего фонового цикла, а
     * синхронный `close()` в [Connection] не даёт дождаться чего-либо.
     * Практический смысл: соединение уже никто не увидит, а освободится.
     *
     * Исключения глотаются: пул уже решил, что соединения нет, и жаловаться
     * некому.
     */
    suspend fun onDiscard(connection: Connection) {}
}
